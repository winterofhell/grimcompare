# The engine's own class tree (GAME::RTTI_ClassInfo, not MSVC RTTI: Game.dll is built without it).
# Every exported `GAME::<Class>::classInfo` static is laid out as: +0x08 name (set at load from the class name
# string), +0x10 parent RTTI_ClassInfo* (a relocated pointer in .data, so readable from the file), +0x18 / +0x20
# child count / array (filled at load). Seen in the dynamic initializer at 0xA8C0 (Skill_AttackProjectile:
# classInfo 0xA59CF0, parent read from +0x10, then appended to the parent's child list).
# Classes without an exported classInfo are found by that initializer: `lea rcx, [name]; call [import];` then
# `mov [classInfo+8], rax` within the next two instructions (checked: it gives the exported 0xA59CF0 back).
# A parent outside the module (Engine.dll) is 0 in the file and printed as "-".
#
# usage: python3 -I re/tools/class_tree.py <Game.dll> re/Game.exports.tsv > re/GameClassTree.tsv
#        python3 -I re/tools/class_tree.py --inc re/GameClassTree.tsv > core/src/class_tree.inc
import re
import struct
import sys


def sections(d):
    pe = struct.unpack_from("<I", d, 0x3C)[0]
    n = struct.unpack_from("<H", d, pe + 6)[0]
    p = pe + 24 + struct.unpack_from("<H", d, pe + 20)[0]
    base = struct.unpack_from("<Q", d, pe + 24 + 24)[0]
    out = []
    for _ in range(n):
        vs, va, rs, rp = struct.unpack_from("<4I", d, p + 8)
        out.append((va, max(vs, rs), rp, rs))
        p += 40
    return base, out


def tree(dll, exports):
    d = open(dll, "rb").read()
    base, secs = sections(d)

    def off(rva):
        for va, size, rp, rs in secs:
            if va <= rva < va + size and rva - va < rs:
                return rp + rva - va
        return None

    def name_at(rva):
        o = off(rva)
        if o is None:
            return None
        e = d.find(b"\0", o, o + 96)
        s = d[o:e]
        return s.decode() if e > o and re.fullmatch(rb"[A-Za-z_][A-Za-z0-9_]*", s) else None

    info = {}
    for va, size, rp, rs in secs[:1]:  # .text
        t = d[rp:rp + rs]
        for m in re.finditer(rb"\x48\x8d\x0d(....)\xff\x15....", t, re.S):
            i = m.start()
            name = name_at(va + i + 7 + struct.unpack("<i", m.group(1))[0])
            if not name:
                continue
            for k in (i + 13, i + 20):
                if t[k:k + 3] == b"\x48\x89\x05":
                    info.setdefault(va + k + 7 + struct.unpack_from("<i", t, k + 3)[0] - 8, name)
                    break
    for line in open(exports):
        rva, mangled, _ = line.rstrip("\n").split("\t")
        m = re.match(r"\?classInfo@(\w+)@GAME@@", mangled)
        if m:
            info[int(rva, 16)] = m.group(1)  # the export wins
    parent = {}
    for rva, name in info.items():
        o = off(rva)
        p = struct.unpack_from("<Q", d, o + 0x10)[0] if o is not None else 0
        parent[name] = info.get(p - base, "-") if p else "-"
    return parent


def inc(tsv):
    rows = []
    for line in open(tsv).read().splitlines()[1:]:
        c, chain = line.split("\t")
        rows.append(f'    {{"{c}", "{chain.split(" ")[0] if chain else ""}"}},')
    print("// Generated by re/tools/class_tree.py --inc re/GameClassTree.tsv. Do not edit.")
    print("// {class, parent}; parent \"\" = root or outside Game.dll.")
    print("\n".join(rows))


if __name__ == "__main__":
    if sys.argv[1] == "--inc":
        inc(sys.argv[2])
        sys.exit(0)
    parent = tree(sys.argv[1], sys.argv[2])
    print("class\tancestors (nearest first)")
    for c in sorted(parent):
        chain, n = [], c
        while parent.get(n, "-") != "-" and len(chain) < 32:
            n = parent[n]
            chain.append(n)
        print(c + "\t" + " ".join(chain))
