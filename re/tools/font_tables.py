# Writes core/src/font_tables.inc: per-size glyph metrics of the two fonts the item tooltip's width depends on,
# from resources/Fonts.arc (FNTX v2, layout read by GraphicsFont2::Initialize, Engine.dll 1.3.1.1 0xAFC90):
#   file   +0x00 'FNTX', +0x04 version (2), +0x18 style count; styles from +0x20
#   style  0x1C bytes: +0x00 size (-> Style+0x98), +0x04 flags (bit 0 bold, bit 1 italic), +0x0C line height,
#          +0x10 glyph count, +0x14 kerning pair count, +0x18 u16 fallback character (-> Style+0xA8)
#   glyph  0x1C bytes = FNTMetric: +0 u16 character, +2 s16 bearing, +4 s16 after, +6 u16 advance
#   kern   8 bytes: u32 (previous << 16 | current), s32 amount (GetKerningAmount 0xB0B30)
# Only the regular styles (flags 0) are written: the tooltip lines measured are never bold or italic.
#
# usage: python3 -I re/tools/font_tables.py "<Grim Dawn>/resources/Fonts.arc" > core/src/font_tables.inc
import struct
import sys

sys.path.insert(0, __file__.rsplit("/", 1)[0])
import arc  # noqa: E402

FACES = [("Jura", "jura.fnt"), ("LinBiolinumSans", "linbiolinum_sansserif.fnt")]
CODES = [0] + list(range(0x20, 0x7F))  # what both fonts hold, in order: U+0000 (the fallback) and ASCII


def styles(data):
    magic, ver = struct.unpack_from("<4sI", data, 0)
    assert magic == b"FNTX" and ver == 2, (magic, ver)
    n = struct.unpack_from("<I", data, 0x18)[0]
    p = 0x20
    for _ in range(n):
        size, flags, _, _, ng, nk = struct.unpack_from("<6I", data, p)
        fallback = struct.unpack_from("<H", data, p + 0x18)[0]
        p += 0x1C
        glyphs = {}
        for _ in range(ng):
            code, bearing, after, advance = struct.unpack_from("<HhhH", data, p)
            glyphs[code] = (bearing, after, advance)
            p += 0x1C
        p += 8 * nk
        yield size, flags, fallback, glyphs, nk
    assert p <= len(data)


def main(path):
    files = dict(arc.read(path))
    print("// Generated by re/tools/font_tables.py from resources/Fonts.arc (Grim Dawn 1.3.1.1). Do not edit.")
    print("// Per regular style: {size, {glyph U+0000, U+0020..U+007E: {bearing, after, advance}}}, file order.")
    for face, name in FACES:
        out = []
        for size, flags, fallback, glyphs, nk in styles(files[name]):
            if flags:
                continue
            # The measure code (font.cpp) has no kerning table and falls back to glyph 0: hold it to that.
            assert nk == 0 and fallback == 0, (name, size, nk, fallback)
            assert sorted(glyphs) == CODES, (name, size)
            for b, a, adv in glyphs.values():
                assert -128 <= b < 128 and -128 <= a < 128 and 0 <= adv < 256, (name, size)
            cells = ", ".join("{%d, %d, %d}" % glyphs[c] for c in CODES)
            out.append("    {%d, {%s}}," % (size, cells))
        print("constexpr Style k%s[] = {" % face)
        print("\n".join(out))
        print("};")


if __name__ == "__main__":
    main(sys.argv[1])
