int difficulty(const snap::Snapshot& s) { return std::clamp(s.difficulty, 0, 2) * 2 + (s.difficulty_ramp > 0 ? 1 : 0); }

Enemy at(double level, int difficulty) {
  const Row* rows = kRows[std::clamp(difficulty, 0, kDifficulties - 1)];
  const Row* hi = std::find_if(rows, rows + kLevels, [&](const Row& r) { return r.level >= level; });
  if (hi == rows) return hi->e;
  if (hi == rows + kLevels) return std::prev(hi)->e;
  const Row* lo = std::prev(hi);
  const double t = (level - lo->level) / (hi->level - lo->level);
  auto mix = [&](double Enemy::*f) { return lo->e.*f + (hi->e.*f - lo->e.*f) * t; };
  Enemy e;
  for (double Enemy::*f : {&Enemy::oa, &Enemy::da, &Enemy::hit, &Enemy::hit_physical, &Enemy::rr, &Enemy::rr_share,
                           &Enemy::crit_damage, &Enemy::boss_rr, &Enemy::boss_rr_share})
    e.*f = mix(f);
  return e;
}

double resist(int type, int difficulty) {
  for (const Resist& r : kResists)
    if (r.type == type) return r.add[std::clamp(difficulty, 0, kDifficulties - 1)];
  return 0;
}

double race_share(const std::vector<std::string>& races) {
  auto lower = [](std::string_view v) {
    std::string out(v);
    for (auto& c : out) c = static_cast<char>(std::tolower(static_cast<unsigned char>(c)));
    return out;
  };
  std::vector<std::string> want;
  for (const auto& r : races)
    if (!r.empty()) want.push_back(lower(r));
  int hit = 0, all = 0;
  for (const Races& g : kRaces) {
    all += g.monsters;
    for (std::size_t at = 0; at <= g.races.size();) {
      const std::size_t end = std::min(g.races.find(',', at), g.races.size());
      if (std::find(want.begin(), want.end(), g.races.substr(at, end - at)) != want.end()) {
        hit += g.monsters;
        break;
      }
      at = end + 1;
    }
  }
  return all ? static_cast<double>(hit) / all : 0;
}

double penalty(int type, int difficulty) {
  for (const Penalty& p : kPenalties)
    if (p.type == type) return p.minus[std::clamp(difficulty, 0, kDifficulties - 1) / 2];
  return 0;
}

